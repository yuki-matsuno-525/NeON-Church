"""ヘブライ語聖書の章節番号を、このサービスの基準（KJV の番号）へ直す。

ユダヤ教の注解（ラシなど）はヘブライ語聖書の番号で書かれている。モーセ五書では
いくつかの箇所で章の区切りが KJV とずれるので、その分だけ直す。ここに無い箇所は
番号が同じ。

表の1行は「ヘブライ語の (章, 節の始め, 節の終わり) → KJV の (章, 節のずれ)」。
例: 創世記 32:2〜33（ヘブライ語）＝ 32:1〜32（KJV）なので、節を 1 引く。
"""

from __future__ import annotations

# slug → [(ヘブライ語の章, 節の始め, 節の終わり, KJV の章, 節に足す数)]
HEBREW_TO_KJV: dict[str, list[tuple[int, int, int, int, int]]] = {
    "genesis": [
        (32, 1, 1, 31, 54),     # 32:1 → 31:55
        (32, 2, 33, 32, -1),    # 32:2-33 → 32:1-32
    ],
    "exodus": [
        (7, 26, 29, 8, -25),    # 7:26-29 → 8:1-4
        (8, 1, 28, 8, 4),       # 8:1-28 → 8:5-32
        (21, 37, 37, 22, -36),  # 21:37 → 22:1
        (22, 1, 30, 22, 1),     # 22:1-30 → 22:2-31
    ],
    "leviticus": [
        (5, 20, 26, 6, -19),    # 5:20-26 → 6:1-7
        (6, 1, 23, 6, 7),       # 6:1-23 → 6:8-30
    ],
    "numbers": [
        (17, 1, 15, 16, 35),    # 17:1-15 → 16:36-50
        (17, 16, 28, 17, -15),  # 17:16-28 → 17:1-13
        (30, 1, 1, 29, 39),     # 30:1 → 29:40
        (30, 2, 17, 30, -1),    # 30:2-17 → 30:1-16
    ],
    "deuteronomy": [
        (13, 1, 1, 12, 31),     # 13:1 → 12:32
        (13, 2, 19, 13, -1),    # 13:2-19 → 13:1-18
        (23, 1, 1, 22, 29),     # 23:1 → 22:30
        (23, 2, 26, 23, -1),    # 23:2-26 → 23:1-25
        (28, 69, 69, 29, -68),  # 28:69 → 29:1
        (29, 1, 28, 29, 1),     # 29:1-28 → 29:2-29
    ],
}


def hebrew_to_kjv(book: str, chapter: int, verse: int) -> tuple[int, int]:
    """ヘブライ語聖書の (章, 節) を KJV の (章, 節) にする。"""
    for heb_ch, v_from, v_to, kjv_ch, shift in HEBREW_TO_KJV.get(book, []):
        if chapter == heb_ch and v_from <= verse <= v_to:
            return kjv_ch, verse + shift
    return chapter, verse
